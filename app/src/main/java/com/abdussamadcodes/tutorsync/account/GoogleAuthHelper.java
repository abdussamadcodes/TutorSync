package com.abdussamadcodes.tutorsync.account;

import android.app.Activity;
import android.content.Context;
import android.os.CancellationSignal;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;
import androidx.core.content.ContextCompat;
import androidx.credentials.ClearCredentialStateRequest;
import androidx.credentials.Credential;
import androidx.credentials.CredentialManager;
import androidx.credentials.CredentialManagerCallback;
import androidx.credentials.CustomCredential;
import androidx.credentials.GetCredentialRequest;
import androidx.credentials.GetCredentialResponse;
import androidx.credentials.exceptions.ClearCredentialException;
import androidx.credentials.exceptions.GetCredentialCancellationException;
import androidx.credentials.exceptions.GetCredentialException;
import androidx.credentials.exceptions.NoCredentialException;

import com.abdussamadcodes.tutorsync.model.Account;
import com.abdussamadcodes.tutorsync.util.AppExecutors;
import com.google.android.libraries.identity.googleid.GetGoogleIdOption;
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption;
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential;
import com.google.firebase.auth.AuthCredential;
import com.google.firebase.auth.FirebaseAuth;
import com.google.firebase.auth.FirebaseUser;
import com.google.firebase.auth.GoogleAuthProvider;

import java.util.concurrent.Executor;

/**
 * Handles modern Android Credential Manager Google Sign-In, Firebase Auth credential exchange,
 * local SQLite Account linking, and Firebase password recovery emails.
 */
public final class GoogleAuthHelper {

    public interface AuthCallback {
        void onSuccess(@NonNull Account localAccount, @NonNull FirebaseUser firebaseUser);
        void onCancelled();
        void onError(@NonNull String message);
    }

    public interface ResetEmailCallback {
        void onSent();
        void onError(@NonNull String message);
    }

    private GoogleAuthHelper() {
    }

    /**
     * Resolves R.string.default_web_client_id generated by the google-services plugin.
     */
    @Nullable
    public static String getWebClientId(@NonNull Context context) {
        int resId = context.getResources().getIdentifier(
                "default_web_client_id", "string", context.getPackageName());
        if (resId == 0) {
            return null;
        }
        String value = context.getString(resId).trim();
        return value.isEmpty() ? null : value;
    }

    /**
     * Launches the Credential Manager bottom sheet for Google Sign-In, falls back to explicit
     * SignInWithGoogle option if no saved credentials are immediately available, authenticates
     * with Firebase, and provisions or links the local SQLite Account row.
     */
    public static void signInWithGoogle(@NonNull Activity activity, @NonNull AuthCallback callback) {
        final String webClientId = getWebClientId(activity);
        if (webClientId == null) {
            callback.onError("Missing default_web_client_id. Verify google-services.json has Google Sign-In enabled in Firebase Console.");
            return;
        }

        final CredentialManager credentialManager = CredentialManager.create(activity);
        final Executor mainExecutor = ContextCompat.getMainExecutor(activity);

        GetGoogleIdOption googleIdOption = new GetGoogleIdOption.Builder()
                .setFilterByAuthorizedAccounts(false)
                .setServerClientId(webClientId)
                .setAutoSelectEnabled(false)
                .build();

        GetCredentialRequest request = new GetCredentialRequest.Builder()
                .addCredentialOption(googleIdOption)
                .build();

        credentialManager.getCredentialAsync(
                activity,
                request,
                new CancellationSignal(),
                mainExecutor,
                new CredentialManagerCallback<GetCredentialResponse, GetCredentialException>() {
                    @Override
                    public void onResult(GetCredentialResponse result) {
                        handleCredentialResult(activity, result.getCredential(), callback);
                    }

                    @Override
                    public void onError(@NonNull GetCredentialException e) {
                        if (e instanceof GetCredentialCancellationException) {
                            callback.onCancelled();
                        } else if (e instanceof NoCredentialException) {
                            launchExplicitGoogleSignInButtonFlow(activity, credentialManager, webClientId, mainExecutor, callback);
                        } else {
                            callback.onError(e.getMessage() != null ? e.getMessage() : "Google Sign-In failed.");
                        }
                    }
                }
        );
    }

    private static void launchExplicitGoogleSignInButtonFlow(
            @NonNull Activity activity,
            @NonNull CredentialManager credentialManager,
            @NonNull String webClientId,
            @NonNull Executor mainExecutor,
            @NonNull AuthCallback callback) {

        GetSignInWithGoogleOption signInWithGoogleOption = new GetSignInWithGoogleOption.Builder(webClientId)
                .build();

        GetCredentialRequest fallbackRequest = new GetCredentialRequest.Builder()
                .addCredentialOption(signInWithGoogleOption)
                .build();

        credentialManager.getCredentialAsync(
                activity,
                fallbackRequest,
                new CancellationSignal(),
                mainExecutor,
                new CredentialManagerCallback<GetCredentialResponse, GetCredentialException>() {
                    @Override
                    public void onResult(GetCredentialResponse result) {
                        handleCredentialResult(activity, result.getCredential(), callback);
                    }

                    @Override
                    public void onError(@NonNull GetCredentialException e) {
                        if (e instanceof GetCredentialCancellationException) {
                            callback.onCancelled();
                        } else {
                            callback.onError(e.getMessage() != null ? e.getMessage() : "No Google account available on this device.");
                        }
                    }
                }
        );
    }

    private static void handleCredentialResult(
            @NonNull Activity activity,
            @NonNull Credential credential,
            @NonNull AuthCallback callback) {

        if (credential instanceof CustomCredential
                && GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL.equals(credential.getType())) {
            try {
                GoogleIdTokenCredential googleIdTokenCredential =
                        GoogleIdTokenCredential.createFrom(credential.getData());
                String idToken = googleIdTokenCredential.getIdToken();
                authenticateWithFirebase(activity, idToken, callback);
            } catch (Exception e) {
                callback.onError("Invalid Google ID token credential.");
            }
        } else {
            callback.onError("Unsupported credential type returned.");
        }
    }

    private static void authenticateWithFirebase(
            @NonNull Activity activity,
            @NonNull String idToken,
            @NonNull AuthCallback callback) {

        AuthCredential credential = GoogleAuthProvider.getCredential(idToken, null);
        FirebaseAuth.getInstance()
                .signInWithCredential(credential)
                .addOnCompleteListener(activity, task -> {
                    if (!task.isSuccessful()) {
                        Exception ex = task.getException();
                        callback.onError(ex != null && ex.getMessage() != null
                                ? ex.getMessage()
                                : "Firebase authentication failed.");
                        return;
                    }

                    FirebaseUser user = FirebaseAuth.getInstance().getCurrentUser();
                    if (user == null || user.getEmail() == null || user.getEmail().trim().isEmpty()) {
                        callback.onError("Google account did not provide an email address.");
                        return;
                    }

                    final Context appContext = activity.getApplicationContext();
                    final String uid = user.getUid();
                    final String email = user.getEmail();
                    final String displayName = user.getDisplayName();

                    AppExecutors.getInstance().diskIO().execute(() -> {
                        LocalAccountStore store = new LocalAccountStore(appContext);
                        Account localAccount = store.getOrCreateGoogleAccount(uid, email, displayName);
                        AppExecutors.getInstance().mainThread().execute(() -> {
                            if (activity.isFinishing() || activity.isDestroyed()) {
                                return;
                            }
                            if (localAccount != null) {
                                callback.onSuccess(localAccount, user);
                            } else {
                                callback.onError("Could not create or link local tutor account.");
                            }
                        });
                    });
                });
    }

    /**
     * Sends a Firebase password reset email for accounts backed by Firebase Email/Password auth.
     */
    public static void sendPasswordResetEmail(@NonNull String email, @NonNull ResetEmailCallback callback) {
        String cleanEmail = email.trim();
        if (cleanEmail.isEmpty()) {
            callback.onError("Email address is required.");
            return;
        }
        FirebaseAuth.getInstance()
                .sendPasswordResetEmail(cleanEmail)
                .addOnCompleteListener(task -> {
                    if (task.isSuccessful()) {
                        callback.onSent();
                    } else {
                        Exception e = task.getException();
                        callback.onError(e != null && e.getMessage() != null
                                ? e.getMessage()
                                : "Unable to send password reset email.");
                    }
                });
    }

    /**
     * Signs out from Firebase and clears the Credential Manager session state.
     */
    public static void signOut(@NonNull Context context) {
        try {
            FirebaseAuth.getInstance().signOut();
        } catch (Exception ignored) {
        }
        try {
            CredentialManager credentialManager = CredentialManager.create(context.getApplicationContext());
            credentialManager.clearCredentialStateAsync(
                    new ClearCredentialStateRequest(),
                    new CancellationSignal(),
                    ContextCompat.getMainExecutor(context.getApplicationContext()),
                    new CredentialManagerCallback<Void, ClearCredentialException>() {
                        @Override
                        public void onResult(Void result) {
                        }

                        @Override
                        public void onError(@NonNull ClearCredentialException e) {
                        }
                    }
            );
        } catch (Exception ignored) {
        }
    }
}